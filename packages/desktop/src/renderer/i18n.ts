const storedLanguage = ((): Language => {
  try {
    return localStorage.getItem('xcode.language') === 'en' ? 'en' : 'zh'
  } catch {
    return 'zh'
  }
})()

void i18n.use(initReactI18next).init({
  resources: { en: { translation: EN } },
  lng: storedLanguage,
  fallbackLng: 'zh',
  keySeparator: false,
  nsSeparator: false,
  interpolation: { escapeValue: false },
  returnNull: false,
})

i18n.on('languageChanged', (language) => {
  try {
    localStorage.setItem('xcode.language', language === 'en' ? 'en' : 'zh')
  } catch {
    // localStorage can be unavailable; the switch still applies for the session.
  }
  document.documentElement.lang = language === 'en' ? 'en' : 'zh-CN'
})

document.documentElement.lang = storedLanguage === 'en' ? 'en' : 'zh-CN'

export function currentLanguage(): Language {
  return i18n.language === 'en' ? 'en' : 'zh'
}

export function setLanguage(language: Language): void {
  void i18n.changeLanguage(language)
}

export default i18n
